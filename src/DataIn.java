    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:

    try {
            // 🟢 DateTime formatter (case-insensitive)
            DateTimeFormatter formatter = new DateTimeFormatterBuilder()
                    .parseCaseInsensitive()
                    .appendPattern("hh:mm a")
                    .toFormatter(Locale.ENGLISH);

            String sleep = jTextField1.getText().trim();
            String wake = jTextField2.getText().trim();

            LocalTime sleepTime = LocalTime.parse(sleep, formatter);
            LocalTime wakeTime = LocalTime.parse(wake, formatter);
            LocalDate today = LocalDate.now();

            LocalDateTime sleepDateTime = today.atTime(sleepTime);
            LocalDateTime wakeDateTime = today.atTime(wakeTime);

            // Handle overnight sleep
            if (wakeTime.isBefore(sleepTime)) {
                wakeDateTime = wakeDateTime.plusDays(1);
            }

            Duration duration = Duration.between(sleepDateTime, wakeDateTime);
            long hours = duration.toHours();
            long minutes = duration.toMinutesPart();
            String quality = (hours >= 6 && hours <= 8) ? "Good Sleep" : "Bad Sleep";

            // Show message
            String result = "Date: " + today +
                    "\nSleep Duration: " + hours + " hrs " + minutes + " min" +
                    "\nQuality: " + quality;
            JOptionPane.showMessageDialog(this, result, "Sleep Report", JOptionPane.INFORMATION_MESSAGE);

            // Save to CSV
            File csvFile = new File(System.getProperty("user.home"), "Book1.csv");
            boolean fileExists = csvFile.exists();

            FileWriter fw = new FileWriter(csvFile, true);
            PrintWriter pw = new PrintWriter(fw);
            if (!fileExists) {
                pw.println("Date,Sleep Time,Wake Time,Hours,Minutes,Quality");
            }
            pw.println(today + "," + sleep + "," + wake + "," + hours + "," + minutes + "," + quality);
            pw.flush();
            pw.close();

            // Update JTable
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.addRow(new Object[]{today, sleep, wake, hours + " hrs " + minutes + " min", quality});

            jTextField1.setText("");
            jTextField2.setText("");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Invalid input! Use format: hh:mm AM/PM\nExample: 11:00 PM",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

